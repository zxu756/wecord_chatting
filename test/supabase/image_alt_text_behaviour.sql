declare
  kept jsonb;
begin
  kept := public.merged_forward_attachment(
    '{"kind":"image","bucket":"chat-images","path":"c1/x.jpg","mime_type":"image/jpeg","size":3,"width":8,"height":6,"blurhash":"LEHV6nWB2yk8","alt":"A red kite over the sea","view_once":true,"junk":1}'::jsonb
  );
  assert kept->>'alt' = 'A red kite over the sea', 'the description is kept';
  assert kept->>'blurhash' = 'LEHV6nWB2yk8', 'the BlurHash still is';
  assert kept->>'path' = 'c1/x.jpg', 'and the path';
  assert not (kept ? 'view_once'), 'view-once is left behind';
  assert not (kept ? 'junk'), 'unknown keys are left behind';

  -- Nothing to keep without one.
  kept := public.merged_forward_attachment(
    '{"kind":"image","bucket":"chat-images","path":"c1/y.jpg","size":3}'::jsonb
  );
  assert not (kept ? 'alt'), 'no description, none added';

  -- Not text: left behind rather than copied.
  kept := public.merged_forward_attachment(
    '{"kind":"image","bucket":"chat-images","path":"c1/z.jpg","size":3,"alt":{"a":1}}'::jsonb
  );
  assert not (kept ? 'alt'), 'an object is not a description';
  kept := public.merged_forward_attachment(
    '{"kind":"image","bucket":"chat-images","path":"c1/z.jpg","size":3,"alt":5}'::jsonb
  );
  assert not (kept ? 'alt'), 'a number is not a description';

  -- Cut at the same 1000 characters as the app.
  kept := public.merged_forward_attachment(
    jsonb_build_object(
      'kind', 'image', 'bucket', 'chat-images', 'path', 'c1/w.jpg', 'size', 3,
      'alt', repeat('a', 1500)
    )
  );
  assert length(kept->>'alt') = 1000, 'a long description is cut';

  -- Other buckets are still refused.
  assert public.merged_forward_attachment(
    '{"kind":"image","bucket":"avatars","path":"c1/x.jpg","alt":"x"}'::jsonb
  ) is null, 'other buckets are refused';
  assert public.merged_forward_attachment(null) is null, 'null stays null';
end $$;

